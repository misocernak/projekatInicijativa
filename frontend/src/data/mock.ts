/** Datumi su relativni u odnosu na danas, da demo uvek izgleda živo. */
function at(daysFromNow: number, hour: number, durationH = 3) {
  const s = new Date()
  s.setDate(s.getDate() + daysFromNow)
  s.setHours(hour, 0, 0, 0)
  const e = new Date(s.getTime() + durationH * 3600_000)
  return { startDate: s.toISOString(), endDate: e.toISOString() }
}

